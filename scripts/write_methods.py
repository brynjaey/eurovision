"""Fill paper/methods_template.md with numbers from data/key_numbers.json -> paper/methods.md.

Placeholders: {{path.to.value}} or {{path.to.value|fmt}}
  path  dot-separated keys into key_numbers.json (list items by index, e.g. edges.years.0)
  fmt   a Python format spec (",", ".3f", "+.3f", ".1f") or "codes" (list -> "CS, WLD, YU")
A missing key stops the script. Literal numbers left in the template (years, versions,
thresholds) are listed at the end so we can check that none of them is a result.
Edit the template, never paper/methods.md.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
K = json.loads((ROOT / "data/key_numbers.json").read_text())
PH = re.compile(r"\{\{([^}|]+)(?:\|([^}]+))?\}\}")


def value(path: str):
    v = K
    for part in path.strip().split("."):
        try:
            v = v[int(part)] if isinstance(v, list) else v[part]
        except (KeyError, IndexError, ValueError) as err:
            raise SystemExit(f"placeholder {{{{{path}}}}}: '{part}' not in key_numbers.json") from err
    return v


def fill(m: re.Match) -> str:
    v, fmt = value(m.group(1)), (m.group(2) or "").strip()
    if fmt == "codes":
        return ", ".join(str(x).upper() for x in v)
    return format(v, fmt) if fmt else str(v)


template = (ROOT / "paper/methods_template.md").read_text()
out = PH.sub(fill, template)
(ROOT / "paper/methods.md").write_text(
    "<!-- GENERATED by scripts/write_methods.py from paper/methods_template.md and data/key_numbers.json. "
    "Do not edit; edit the template and rerun. -->\n\n" + out)

body = re.sub(r"<!--.*?-->", "", PH.sub("", template), flags=re.S)  # text outside placeholders and comments
literals = sorted(set(re.findall(r"(?<![\w.])\d[\d,.–-]*\d|(?<![\w.])\d(?![\w])", body)))
print(f"paper/methods.md written: {len(PH.findall(template))} numbers filled from key_numbers.json")
print("literal numbers in the template (check each is a parameter, date or version, not a result):")
print(" ".join(literals))
