"""Build the paper text files from templates and data/key_numbers.json.

Input:  paper/methods_template.md   Methods text with placeholders (edit this, not the outputs)
        figures/captions.md         figure captions
        data/key_numbers.json
Output: paper/methods.md            Methods with numbers filled in (for reading)
        paper/methods.tex           the same as LaTeX, \\input by paper/main.tex
        paper/figure_floats.tex     figure environments with the captions, \\input by paper/main.tex

Placeholders: {{path.to.value}} or {{path.to.value|fmt}}
  path  dot-separated keys into key_numbers.json (list items by index, e.g. edges.years.0)
  fmt   a Python format spec (",", ".3f", "+.3f") or "codes" (list -> "CS, WLD, YU")
A missing key stops the script. Literal numbers left in the template (years, versions,
thresholds) are listed at the end so we can check that none of them is a result.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
K = json.loads((ROOT / "data/key_numbers.json").read_text())
PH = re.compile(r"\{\{([^}|]+)(?:\|([^}]+))?\}\}")
GENERATED = "Generated by scripts/write_paper.py; do not edit (edit the template / figures/captions.md and rerun)."


def value(path: str):
    v = K
    for part in path.strip().split("."):
        try:
            v = v[int(part)] if isinstance(v, list) else v[part]
        except (KeyError, IndexError, ValueError) as err:
            raise SystemExit(f"placeholder {{{{{path}}}}}: '{part}' not in key_numbers.json") from err
    return v


def fill(m: re.Match) -> str:
    v, fmt = value(m.group(1)), (m.group(2) or "").strip()
    if fmt == "codes":
        return ", ".join(str(x).upper() for x in v)
    return format(v, fmt) if fmt else str(v)


def to_latex(md: str) -> str:
    """Our small Markdown subset -> LaTeX. Text inside $...$ is left as it is (it is already LaTeX)."""
    md = re.sub(r"<!--.*?-->", "", md, flags=re.S).strip()
    parts = re.split(r"(\$[^$]+\$)", md)
    out = []
    for i, t in enumerate(parts):
        if i % 2:  # math
            out.append(t)
            continue
        t = re.sub(r"\[@([^\]]+)\]", lambda m: "\\cite{" + ",".join(k.strip(" @") for k in m.group(1).split(";")) + "}", t)
        t = re.sub(r"`([^`]+)`", lambda m: "\\texttt{" + m.group(1).replace("_", "\\_") + "}", t)
        t = re.sub(r"(?<!\\)([%&#])", r"\\\1", t)                            # LaTeX special characters
        t = re.sub(r"(?<![\w-])-(\d)", r"$-$\1", t)                          # negative numbers
        t = re.sub(r"(?<!\\)_(?![^{]*\})", r"\\_", t)                        # underscores outside braces
        t = re.sub(r"(\d(?:\.\d+)?)e-(\d+)", lambda m: f"${m.group(1)}\\times10^{{-{int(m.group(2))}}}$", t)
        t = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", t)
        t = re.sub(r"\*(.+?)\*", r"\\textit{\1}", t)
        t = (t.replace("−", "$-$").replace("≥", "$\\geq$").replace("×", "$\\times$").replace("≈", "$\\approx$")
              .replace('"', "''").replace("TODO (group):", "\\textbf{TODO (group):}"))
        t = re.sub(r"(?<=\s)''(?=\w)", "``", t)  # opening double quotes
        out.append(t)
    return "".join(out)


# 1. Methods
template = (ROOT / "paper/methods_template.md").read_text()
filled = PH.sub(fill, template)
(ROOT / "paper/methods.md").write_text(f"<!-- {GENERATED} -->\n\n" + re.sub(r"<!--.*?-->\s*", "", filled, count=1, flags=re.S))
(ROOT / "paper/methods.tex").write_text(f"% {GENERATED}\n" + to_latex(filled) + "\n")

# 2. Figure floats from figures/captions.md ("## Fig. N — `file.pdf` ..." followed by the caption)
caps = (ROOT / "figures/captions.md").read_text()
floats = [f"% {GENERATED}"]
for head, body in re.findall(r"^## (Fig\. \d+.*?)\n(.*?)(?=^## |\Z)", caps, flags=re.S | re.M):
    name = re.search(r"`([^`]+)\.pdf`", head).group(1)
    wide = "two-column" in head
    env = "figure*" if wide else "figure"
    text = to_latex(" ".join(PH.sub(fill, body).split()))  # captions may use {{placeholders}} too
    floats += [f"\\begin{{{env}}}[tbhp]", "\\centering",
               f"\\includegraphics[width={'0.9' if wide else ''}\\{'textwidth' if wide else 'linewidth'}]{{{name}}}",
               f"\\caption{{{text}}}", f"\\label{{fig:{name.split('_')[0]}}}", f"\\end{{{env}}}", ""]
(ROOT / "paper/figure_floats.tex").write_text("\n".join(floats))

# 3. Report
body = re.sub(r"<!--.*?-->", "", PH.sub("", template), flags=re.S)
literals = sorted(set(re.findall(r"(?<![\w.])\d[\d,.–-]*\d|(?<![\w.])\d(?![\w])", body)))
words = len(re.sub(r"<!--.*?-->", "", filled, flags=re.S).split())
print(f"paper/methods.md + methods.tex: {len(PH.findall(template))} numbers from key_numbers.json, {words} words")
print(f"paper/figure_floats.tex: {len(floats) // 7} figures")
print("literal numbers in the template (check each is a parameter, date or version, not a result):")
print(" ".join(literals))
